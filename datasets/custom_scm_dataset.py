import json
import os
from dataclasses import dataclass

import numpy as np

from dataset_generator.scm_graph import graph_of, node_info, node_roles
from datasets.tabular_dataset import TabularDataset

DEFAULT_DATA_DIR = "/lustre/fswork/projects/rech/ycq/ufb58bn/DataRemi/custom_scm_data"


def custom_scm_data_dir():
    """Where the generated tables live: $CUSTOM_SCM_DATA, else the project's lustre folder."""
    return os.environ.get("CUSTOM_SCM_DATA", DEFAULT_DATA_DIR)


def custom_scm_paths(name, data_dir=None):
    """The (table, metadata) file paths of a generated table."""
    data_dir = data_dir or custom_scm_data_dir()
    return os.path.join(data_dir, f"{name}.npz"), os.path.join(data_dir, f"{name}.json")


@dataclass
class CustomSCMDataset(TabularDataset):
    """A table generated by `dataset_generator`, with the causal model it was drawn from.

    On top of the TabularDataset fields, everything needed to act on a node of the causal graph
    (a chain or a DAG, see dataset_generator/scm_graph.py):

    Attributes:
        metadata (dict): The content of the table's json file (config, seed, edges, ...).
        nodes (np.ndarray): Every node of the graph, of shape (n_samples, n_nodes), in the
            row order of `X`/`y` (before the train/test split).
        noise (np.ndarray): The noise drawn at every node, same shape as `nodes`, so that a
            node can be changed and its descendants recomputed with the same noise.
    """

    metadata: dict
    nodes: np.ndarray
    noise: np.ndarray

    @classmethod
    def load(cls, name, test_size=0.33, seed=42, data_dir=None):
        """Load a stored table and split it in a train and a test set.

        Args:
            name (str): The name of the table (the file name without extension).
            test_size (float, optional): The test proportion. Defaults to 0.33.
            seed (int, optional): The seed of the split. Defaults to 42.
            data_dir (str, optional): The folder of the tables. Defaults to
                `custom_scm_data_dir()`.

        Returns:
            CustomSCMDataset: The split dataset.
        """
        table_path, metadata_path = custom_scm_paths(name, data_dir)
        if not (os.path.exists(table_path) and os.path.exists(metadata_path)):
            raise FileNotFoundError(f"No generated table {name!r} in {os.path.dirname(table_path)}")
        with open(metadata_path) as file:
            metadata = json.load(file)
        table = np.load(table_path)
        base = TabularDataset.from_xy(name, table["X"], table["y"], test_size=test_size, seed=seed)
        return cls(
            **vars(base), metadata=metadata, nodes=table["nodes"], noise=table["noise"]
        )

    @property
    def target_node(self):
        return self.metadata["target_node"]

    @property
    def feature_nodes(self):
        """The node behind every column of X, in column order."""
        return self.metadata["feature_nodes"]

    @property
    def graph(self):
        """The causal graph, see `dataset_generator.scm_graph`."""
        return graph_of(self.metadata)

    @property
    def roles(self):
        """The role of every node towards the target: target, parent, child, spouse or outside
        (the Markov blanket is made of the parents, children and spouses)."""
        return node_roles(self.graph["parents"], self.target_node)

    @property
    def info(self):
        """The depth, number of ancestors and of descendants of every node."""
        return node_info(self.graph["parents"])

    def column_of(self, node):
        """The column of X holding `node`, or None for the target node."""
        return self.feature_nodes.index(node) if node in self.feature_nodes else None
