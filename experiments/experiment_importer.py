from functools import partial

from experiments.causal_chain import ChainCondRandomize, ChainEdgeShuffle, ChainNoise, ChainRandomize
from experiments.context_swap import ContextSwap
from experiments.perturbations import (
    ColRemove,
    ColShuffle,
    RandomLabels,
    RowRemove,
    RowShuffle,
    ValueNoise,
)
from experiments.target_column import AltTarget

_CHAIN = (ChainNoise, ChainRandomize, ChainEdgeShuffle)

EXPERIMENTS = {
    experiment.name: experiment
    for experiment in (RowShuffle, ColShuffle, RandomLabels, ColRemove, RowRemove, ValueNoise, AltTarget)
    + _CHAIN
    + (ContextSwap,)
}
# The chain perturbations with the perturbed node's descendants not recomputed: one column changes.
EXPERIMENTS.update({f"{chain.name}_local": partial(chain, propagate=False) for chain in _CHAIN})
# The conditional permutation, kept out of the groups (it is what the Markov blanket benchmark
# perturbs with, detectors/pfm_probe.py), both ways like the others.
EXPERIMENTS["chain_condrandomize"] = ChainCondRandomize
EXPERIMENTS["chain_condrandomize_local"] = partial(ChainCondRandomize, propagate=False)

_PERTURBATIONS = ["row_shuffle", "col_shuffle", "random_labels", "col_remove", "row_remove", "value_noise"]
_CHAIN_NAMES = [chain.name for chain in _CHAIN]

# Groups of experiments plotted together on a single figure.
EXPERIMENT_GROUPS = {
    # The 2x3 grid of the original test.py, in its original panel order.
    "perturbations": _PERTURBATIONS,
    # every experiment that runs on any dataset
    "all": _PERTURBATIONS + ["alt_target"],
    # needs a dataset generated by dataset_generator (custom SCM)
    "chain": _CHAIN_NAMES,
    "chain_local": [f"{name}_local" for name in _CHAIN_NAMES],
    # needs a table of a group (dataset_generator/cond_groups.py), run on its baseline
    "context": ["context_swap"],
    # both, on one figure: what a perturbation does, propagated or not. The edge shuffles are left
    # out: they fail on a DAG with several roots, where the node k+1 of level k can be a root.
    "chain_all": ["chain_noise", "chain_randomize", "chain_noise_local", "chain_randomize_local"],
    # the column-only perturbations alone: what the Markov blanket benchmark reads, and all that
    # runs on real measurements (a Causal Chamber table has no structural equations to propagate)
    "blanket": ["chain_noise_local", "chain_randomize_local"],
}


def experiment_importer(exp_name, dict_params=None):
    """Import the experiments to run under the given name.

    Args:
        exp_name (str): The name of an experiment or of a group of experiments,
            in EXPERIMENTS or EXPERIMENT_GROUPS.
        dict_params (dict, optional): Parameters forwarded to the experiments,
            to do ablations. Defaults to None.

    Returns:
        list: The instantiated experiments.

    Raises:
        ValueError: If the experiment is not implemented.
    """
    print(f"Importing experiment {exp_name} ...")
    dict_params = {} if dict_params is None else dict_params

    if exp_name in EXPERIMENT_GROUPS:
        names = EXPERIMENT_GROUPS[exp_name]
    elif exp_name in EXPERIMENTS:
        names = [exp_name]
    else:
        raise ValueError(
            f"Experiment {exp_name} not implemented ! Available: "
            f"{list(EXPERIMENTS) + list(EXPERIMENT_GROUPS)}"
        )

    return [EXPERIMENTS[name](**dict_params) for name in names]
